const SPEC: &str = include_str!("../../../../spec/regex_unicode.txt");

/// Go `unicode.MaxRune`.
const MAX_RUNE: i32 = 0x10FFFF;
/// Go `minFold` / `maxFold`: the range of code points that fold.
const MIN_FOLD: i32 = 0x0041;
const MAX_FOLD: i32 = 0x1E943;

/// Inclusive runs `(lo, hi)`, sorted and disjoint.
type Runs = Vec<(i32, i32)>;

struct Tables {
    categories: HashMap<&'static str, Runs>,
    fold_category: HashMap<&'static str, Runs>,
    scripts: HashMap<&'static str, Runs>,
    fold_script: HashMap<&'static str, Runs>,
    /// `canonicalName(alias)` → category (Go `aliases.categories`).
    alias_categories: HashMap<Vec<u8>, &'static str>,
    /// `canonicalName(script)` → script (Go `aliases.scripts`).
    alias_scripts: HashMap<Vec<u8>, &'static str>,
    /// Go `unicode.SimpleFold`, for code points that fold.
    simple_fold: HashMap<i32, i32>,
}

/// Go's tables, read once. The panics below cannot happen at run time:
/// the file is compiled in, and `TestSpecFiles` (tests/spec_test.go)
/// keeps it exactly what Go generates, so a malformed line is a build-time
/// mistake that every regex test would show.
fn tables() -> &'static Tables {
    static TABLES: OnceLock<Tables> = OnceLock::new();
    TABLES.get_or_init(|| {
        let mut t = Tables {
            categories: HashMap::new(),
            fold_category: HashMap::new(),
            scripts: HashMap::new(),
            fold_script: HashMap::new(),
            alias_categories: HashMap::new(),
            alias_scripts: HashMap::new(),
            simple_fold: HashMap::new(),
        };
        let hex = |s: &str| {
            i32::from_str_radix(s, 16)
                .unwrap_or_else(|_| panic!("spec/regex_unicode.txt: bad number {s:?}"))
        };
        let runs = |fields: std::str::Split<'static, char>| -> Runs {
            fields
                .map(|f| match f.split_once('-') {
                    Some((lo, hi)) => (hex(lo), hex(hi)),
                    None => (hex(f), hex(f)),
                })
                .collect()
        };
        for line in SPEC.lines() {
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let mut f = line.split(' ');
            let kind = f.next().unwrap_or("");
            match kind {
                "cat" | "foldcat" | "script" | "foldscript" => {
                    let name = f.next().expect("spec/regex_unicode.txt: no name");
                    let map = match kind {
                        "cat" => &mut t.categories,
                        "foldcat" => &mut t.fold_category,
                        "script" => &mut t.scripts,
                        _ => &mut t.fold_script,
                    };
                    map.insert(name, runs(f));
                }
                "alias" => {
                    let (Some(alias), Some(cat)) = (f.next(), f.next()) else {
                        panic!("spec/regex_unicode.txt: bad line {line:?}");
                    };
                    t.alias_categories
                        .insert(canonical_name(alias.as_bytes()), cat);
                }
                "fold" => {
                    let orbit: Vec<i32> = f.map(hex).collect();
                    for (i, &c) in orbit.iter().enumerate() {
                        t.simple_fold.insert(c, orbit[(i + 1) % orbit.len()]);
                    }
                }
                _ => panic!("spec/regex_unicode.txt: bad line {line:?}"),
            }
        }
        let scripts: Vec<&'static str> = t.scripts.keys().copied().collect();
        for s in scripts {
            t.alias_scripts.insert(canonical_name(s.as_bytes()), s);
        }
        t
    })
}

/// Go `unicode.SimpleFold`.
fn simple_fold(r: i32) -> i32 {
    if !(0..=MAX_RUNE).contains(&r) {
        return r;
    }
    tables().simple_fold.get(&r).copied().unwrap_or(r)
}

/// Go `minFoldRune`.
fn min_fold_rune(r: i32) -> i32 {
    if !(MIN_FOLD..=MAX_FOLD).contains(&r) {
        return r;
    }
    let mut m = r;
    let mut f = simple_fold(r);
    while f != r {
        m = m.min(f);
        f = simple_fold(f);
    }
    m
}

/// Go `canonicalName`: `_`, `-` and space dropped, first letter upper
/// case, the rest lower case (ASCII only).
fn canonical_name(name: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(name.len());
    let mut first = true;
    for &b in name {
        let c = match b {
            b'_' | b'-' | b' ' => continue,
            _ if first => {
                first = false;
                b.to_ascii_uppercase()
            }
            _ => b.to_ascii_lowercase(),
        };
        out.push(c);
    }
    out
}

/// A Unicode class table as Go's `unicodeTable` returns it.
enum Table {
    Runs(&'static [(i32, i32)]),
    Nil,
}

const ANY: &[(i32, i32)] = &[(0, MAX_RUNE)];
const ASCII: &[(i32, i32)] = &[(0, 0x7F)];
const ASCII_FOLD: &[(i32, i32)] = &[(0, 0x7F), (0x17F, 0x17F), (0x212A, 0x212A)];

/// What Go's `unicodeTable` returns: table, fold table, sign.
type UnicodeTable = (&'static [(i32, i32)], Table, i32);

/// Go `unicodeTable`, or `None` for an unknown name.
fn unicode_table(name: &[u8]) -> Option<UnicodeTable> {
    let t = tables();
    let name = canonical_name(name);
    let get = |m: &'static HashMap<&'static str, Runs>, k: &str| -> Table {
        m.get(k).map_or(Table::Nil, |r| Table::Runs(r))
    };
    match name.as_slice() {
        b"Any" => return Some((ANY, Table::Runs(ANY), 1)),
        b"Assigned" => {
            let cn = t.categories.get("Cn")?;
            return Some((cn, Table::Runs(cn), -1));
        }
        b"Ascii" => return Some((ASCII, Table::Runs(ASCII_FOLD), 1)),
        b"Lc" => {
            let lc = t.categories.get("LC")?;
            return Some((lc, get(&t.fold_category, "LC"), 1));
        }
        _ => {}
    }
    let key = std::str::from_utf8(&name).ok()?;
    if let Some(r) = t.categories.get(key) {
        return Some((r, get(&t.fold_category, key), 1));
    }
    if let Some(r) = t.scripts.get(key) {
        return Some((r, get(&t.fold_script, key), 1));
    }
    if let Some(&actual) = t.alias_categories.get(&name) {
        let r = t.categories.get(actual)?;
        return Some((r, get(&t.fold_category, actual), 1));
    }
    if let Some(&actual) = t.alias_scripts.get(&name) {
        let r = t.scripts.get(actual)?;
        return Some((r, get(&t.fold_script, actual), 1));
    }
    None
}

/// Go `perlGroup` (`perl_groups.go`): ASCII only.
fn perl_group(s: &[u8]) -> Option<(i32, &'static [i32])> {
    const D: &[i32] = &[0x30, 0x39];
    const S: &[i32] = &[0x9, 0xa, 0xc, 0xd, 0x20, 0x20];
    const W: &[i32] = &[0x30, 0x39, 0x41, 0x5a, 0x5f, 0x5f, 0x61, 0x7a];
    Some(match s {
        b"\\d" => (1, D),
        b"\\D" => (-1, D),
        b"\\s" => (1, S),
        b"\\S" => (-1, S),
        b"\\w" => (1, W),
        b"\\W" => (-1, W),
        _ => return None,
    })
}

/// Go `posixGroup` (`perl_groups.go`).
fn posix_group(name: &[u8]) -> Option<(i32, &'static [i32])> {
    let (neg, base) = match name.strip_prefix(b"[:^") {
        Some(rest) => (true, rest),
        None => (false, name.strip_prefix(b"[:")?),
    };
    let class: &'static [i32] = match base {
        b"alnum:]" => &[0x30, 0x39, 0x41, 0x5a, 0x61, 0x7a],
        b"alpha:]" => &[0x41, 0x5a, 0x61, 0x7a],
        b"ascii:]" => &[0x0, 0x7f],
        b"blank:]" => &[0x9, 0x9, 0x20, 0x20],
        b"cntrl:]" => &[0x0, 0x1f, 0x7f, 0x7f],
        b"digit:]" => &[0x30, 0x39],
        b"graph:]" => &[0x21, 0x7e],
        b"lower:]" => &[0x61, 0x7a],
        b"print:]" => &[0x20, 0x7e],
        b"punct:]" => &[0x21, 0x2f, 0x3a, 0x40, 0x5b, 0x60, 0x7b, 0x7e],
        b"space:]" => &[0x9, 0xd, 0x20, 0x20],
        b"upper:]" => &[0x41, 0x5a],
        b"word:]" => &[0x30, 0x39, 0x41, 0x5a, 0x5f, 0x5f, 0x61, 0x7a],
        b"xdigit:]" => &[0x30, 0x39, 0x41, 0x46, 0x61, 0x66],
        _ => return None,
    };
    Some((if neg { -1 } else { 1 }, class))
}

// ---------------------------------------------------------------------
// Character class helpers (Go `appendRange` and friends). A class is a
// flat list of rune pairs `lo, hi, lo, hi, ...`, as in Go.
// ---------------------------------------------------------------------

/// Go `appendRange`: merges with one of the last two ranges if possible.
fn append_range(r: &mut Vec<i32>, lo: i32, hi: i32) {
    let n = r.len();
    for i in [2, 4] {
        if n >= i {
            let (rlo, rhi) = (r[n - i], r[n - i + 1]);
            if lo <= rhi + 1 && rlo <= hi + 1 {
                if lo < rlo {
                    r[n - i] = lo;
                }
                if hi > rhi {
                    r[n - i + 1] = hi;
                }
                return;
            }
        }
    }
    r.extend([lo, hi]);
}

/// Go `appendFoldedRange`.
fn append_folded_range(r: &mut Vec<i32>, mut lo: i32, mut hi: i32) {
    if (lo <= MIN_FOLD && hi >= MAX_FOLD) || hi < MIN_FOLD || lo > MAX_FOLD {
        append_range(r, lo, hi);
        return;
    }
    if lo < MIN_FOLD {
        append_range(r, lo, MIN_FOLD - 1);
        lo = MIN_FOLD;
    }
    if hi > MAX_FOLD {
        append_range(r, MAX_FOLD + 1, hi);
        hi = MAX_FOLD;
    }
    for c in lo..=hi {
        append_range(r, c, c);
        let mut f = simple_fold(c);
        while f != c {
            append_range(r, f, f);
            f = simple_fold(f);
        }
    }
}

fn append_literal(r: &mut Vec<i32>, x: i32, flags: u16) {
    if flags & FOLD_CASE != 0 {
        append_folded_range(r, x, x);
    } else {
        append_range(r, x, x);
    }
}

fn append_class(r: &mut Vec<i32>, x: &[i32]) {
    for p in x.chunks_exact(2) {
        append_range(r, p[0], p[1]);
    }
}

fn append_folded_class(r: &mut Vec<i32>, x: &[i32]) {
    for p in x.chunks_exact(2) {
        append_folded_range(r, p[0], p[1]);
    }
}

fn append_negated_class(r: &mut Vec<i32>, x: &[i32]) {
    let mut next_lo = 0;
    for p in x.chunks_exact(2) {
        if next_lo < p[0] {
            append_range(r, next_lo, p[0] - 1);
        }
        next_lo = p[1] + 1;
    }
    if next_lo <= MAX_RUNE {
        append_range(r, next_lo, MAX_RUNE);
    }
}

fn append_table(r: &mut Vec<i32>, x: &[(i32, i32)]) {
    for &(lo, hi) in x {
        append_range(r, lo, hi);
    }
}

fn append_negated_table(r: &mut Vec<i32>, x: &[(i32, i32)]) {
    let mut next_lo = 0;
    for &(lo, hi) in x {
        if next_lo < lo {
            append_range(r, next_lo, lo - 1);
        }
        next_lo = hi + 1;
    }
    if next_lo <= MAX_RUNE {
        append_range(r, next_lo, MAX_RUNE);
    }
}

/// Go `cleanClass`: sort by low end (longer first on ties) and merge.
fn clean_class(r: &mut Vec<i32>) {
    let mut pairs: Vec<(i32, i32)> = r.chunks_exact(2).map(|p| (p[0], p[1])).collect();
    pairs.sort_by(|a, b| a.0.cmp(&b.0).then(b.1.cmp(&a.1)));
    r.clear();
    for (lo, hi) in pairs {
        if let Some(last) = r.last_mut()
            && lo <= *last + 1
        {
            if hi > *last {
                *last = hi;
            }
            continue;
        }
        r.extend([lo, hi]);
    }
}

/// Go `negateClass` (of a clean class).
fn negate_class(r: &mut Vec<i32>) {
    let old = std::mem::take(r);
    append_negated_class(r, &old);
}

