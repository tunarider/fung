// Go `syntax.Flags`.
const FOLD_CASE: u16 = 1;
const CLASS_NL: u16 = 1 << 2;
const DOT_NL: u16 = 1 << 3;
const ONE_LINE: u16 = 1 << 4;
const NON_GREEDY: u16 = 1 << 5;
const PERL_X: u16 = 1 << 6;
const UNICODE_GROUPS: u16 = 1 << 7;
const WAS_DOLLAR: u16 = 1 << 8;
/// Go `syntax.Perl`, the flags `regexp.Compile` uses.
const PERL: u16 = CLASS_NL | ONE_LINE | PERL_X | UNICODE_GROUPS;

/// Go `syntax.Op`, with Go's numbering: factoring compares ops by order.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug)]
enum Op {
    NoMatch = 1,
    EmptyMatch,
    Literal,
    CharClass,
    AnyCharNotNL,
    AnyChar,
    BeginLine,
    EndLine,
    BeginText,
    EndText,
    WordBoundary,
    NoWordBoundary,
    Capture,
    Star,
    Plus,
    Quest,
    Repeat,
    Concat,
    Alternate,
    /// Go `opLeftParen` (`opPseudo`): a pseudo-op on the parse stack.
    LeftParen = 128,
    VerticalBar,
}

#[derive(Clone)]
struct Node {
    op: Op,
    flags: u16,
    sub: Vec<usize>,
    rune: Vec<i32>,
    min: i32,
    max: i32,
    cap: i32,
    name: String,
}

impl Node {
    fn new(op: Op) -> Node {
        Node {
            op,
            flags: 0,
            sub: Vec::new(),
            rune: Vec::new(),
            min: 0,
            max: 0,
            cap: 0,
            name: String::new(),
        }
    }

    fn clone_shape(&self) -> Shape {
        Shape {
            op: self.op,
            runes: self.rune.len(),
            sub: self.sub.clone(),
            min: self.min,
            max: self.max,
        }
    }
}

/// The parts of a node `calc_size` reads, copied so the recursion can
/// borrow the parser mutably.
struct Shape {
    op: Op,
    runes: usize,
    sub: Vec<usize>,
    min: i32,
    max: i32,
}

// Go's error codes (`syntax.ErrorCode`).
const ERR_INVALID_CHAR_RANGE: &str = "invalid character class range";
const ERR_INVALID_ESCAPE: &str = "invalid escape sequence";
const ERR_INVALID_NAMED_CAPTURE: &str = "invalid named capture";
const ERR_INVALID_PERL_OP: &str = "invalid or unsupported Perl syntax";
const ERR_INVALID_REPEAT_OP: &str = "invalid nested repetition operator";
const ERR_INVALID_REPEAT_SIZE: &str = "invalid repeat count";
const ERR_MISSING_BRACKET: &str = "missing closing ]";
const ERR_MISSING_PAREN: &str = "missing closing )";
const ERR_MISSING_REPEAT_ARGUMENT: &str = "missing argument to repetition operator";
const ERR_TRAILING_BACKSLASH: &str = "trailing backslash at end of expression";
const ERR_UNEXPECTED_PAREN: &str = "unexpected )";
const ERR_NESTING_DEPTH: &str = "expression nests too deeply";
const ERR_LARGE: &str = "expression too large";
const ERR_INTERNAL: &str = "regexp/syntax: internal error";

/// A parse failure. Go panics with `ErrLarge` and `ErrNestingDepth` and
/// reports the whole pattern for them.
enum Fail {
    Syntax(&'static str, String),
    Large,
    Nesting,
}

type Res<T> = Result<T, Fail>;

/// Go `maxHeight`, `maxSize`, `maxRunes`.
const MAX_HEIGHT: i32 = 1000;
const MAX_SIZE: i64 = (128 << 20) / (5 * 8);
const MAX_RUNES: i64 = (128 << 20) / 4;

/// Go `syntax.parser`. Positions are byte offsets into the pattern: every
/// string Go's parser slices is a suffix of the pattern.
struct Parser<'a> {
    s: &'a str,
    flags: u16,
    stack: Vec<usize>,
    nodes: Vec<Node>,
    /// Go's free list (LIFO).
    free: Vec<usize>,
    num_cap: i32,
    num_regexp: i64,
    num_runes: i64,
    repeats: i64,
    height: Option<HashMap<usize, i32>>,
    size: Option<HashMap<usize, i64>>,
}

fn is_alnum(c: i32) -> bool {
    (0x30..=0x39).contains(&c) || (0x41..=0x5a).contains(&c) || (0x61..=0x7a).contains(&c)
}

fn unhex(c: i32) -> i32 {
    match c {
        0x30..=0x39 => c - 0x30,
        0x61..=0x66 => c - 0x61 + 10,
        0x41..=0x46 => c - 0x41 + 10,
        _ => -1,
    }
}

/// Go `parseInt`: a decimal without leading zeros; -1 when 1e8 or more.
fn parse_int(b: &[u8], mut i: usize) -> Option<(i32, usize)> {
    if i >= b.len() || !b[i].is_ascii_digit() {
        return None;
    }
    if b.len() - i >= 2 && b[i] == b'0' && b[i + 1].is_ascii_digit() {
        return None;
    }
    let start = i;
    while i < b.len() && b[i].is_ascii_digit() {
        i += 1;
    }
    let mut n: i32 = 0;
    for &d in &b[start..i] {
        if n >= 100_000_000 {
            n = -1;
            break;
        }
        n = n * 10 + i32::from(d - b'0');
    }
    Some((n, i))
}

impl<'a> Parser<'a> {
    fn b(&self) -> &'a [u8] {
        self.s.as_bytes()
    }

    /// The pattern text `[a, b)`.
    fn text(&self, a: usize, b: usize) -> String {
        String::from_utf8_lossy(self.b().get(a..b).unwrap_or_default()).into_owned()
    }

    fn syntax<T>(&self, code: &'static str, a: usize, b: usize) -> Res<T> {
        Err(Fail::Syntax(code, self.text(a, b)))
    }

    /// Go `nextRune` from `pos`: the empty string gives U+FFFD, length 0.
    fn next_rune(&self, pos: usize) -> (i32, usize) {
        match self.s.get(pos..).and_then(|t| t.chars().next()) {
            Some(c) => (c as i32, pos + c.len_utf8()),
            None if pos >= self.s.len() => (0xFFFD, pos),
            // Not a character boundary: cannot happen, positions only
            // move by whole characters or ASCII bytes.
            None => (0xFFFD, pos + 1),
        }
    }

    fn at(&self, pos: usize) -> Option<u8> {
        self.b().get(pos).copied()
    }

    fn new_regexp(&mut self, op: Op) -> usize {
        if let Some(ix) = self.free.pop() {
            self.nodes[ix] = Node::new(op);
            ix
        } else {
            self.nodes.push(Node::new(op));
            self.num_regexp += 1;
            self.nodes.len() - 1
        }
    }

    fn reuse(&mut self, ix: usize) {
        if let Some(h) = &mut self.height {
            h.remove(&ix);
        }
        self.free.push(ix);
    }

    fn check_limits(&mut self, ix: usize) -> Res<()> {
        if self.num_runes > MAX_RUNES {
            return Err(Fail::Large);
        }
        self.check_size(ix)?;
        self.check_height(ix)
    }

    fn check_size(&mut self, ix: usize) -> Res<()> {
        if self.size.is_none() {
            if self.repeats == 0 {
                self.repeats = 1;
            }
            let re = &self.nodes[ix];
            if re.op == Op::Repeat {
                let mut n = re.max;
                if n == -1 {
                    n = re.min;
                }
                if n <= 0 {
                    n = 1;
                }
                if i64::from(n) > MAX_SIZE / self.repeats {
                    self.repeats = MAX_SIZE;
                } else {
                    self.repeats *= i64::from(n);
                }
            }
            if self.num_regexp < MAX_SIZE / self.repeats {
                return Ok(());
            }
            self.size = Some(HashMap::new());
            for re in self.stack.clone() {
                self.check_size(re)?;
            }
        }
        if self.calc_size(ix, true) > MAX_SIZE {
            return Err(Fail::Large);
        }
        Ok(())
    }

    fn calc_size(&mut self, ix: usize, force: bool) -> i64 {
        if !force && let Some(&n) = self.size.as_ref().and_then(|m| m.get(&ix)) {
            return n;
        }
        let re = self.nodes[ix].clone_shape();
        let size = match re.op {
            Op::Literal => re.runes as i64,
            Op::Capture | Op::Star => 2 + self.calc_size(re.sub[0], false),
            Op::Plus | Op::Quest => 1 + self.calc_size(re.sub[0], false),
            Op::Concat => re.sub.iter().map(|&s| self.calc_size(s, false)).sum(),
            Op::Alternate => {
                let mut n: i64 = re.sub.iter().map(|&s| self.calc_size(s, false)).sum();
                if re.sub.len() > 1 {
                    n += re.sub.len() as i64 - 1;
                }
                n
            }
            Op::Repeat => {
                let sub = self.calc_size(re.sub[0], false);
                if re.max == -1 {
                    if re.min == 0 {
                        2 + sub
                    } else {
                        1 + i64::from(re.min) * sub
                    }
                } else {
                    i64::from(re.max) * sub + i64::from(re.max - re.min)
                }
            }
            _ => 0,
        };
        let size = size.max(1);
        if let Some(m) = &mut self.size {
            m.insert(ix, size);
        }
        size
    }

    fn check_height(&mut self, ix: usize) -> Res<()> {
        if self.num_regexp < i64::from(MAX_HEIGHT) {
            return Ok(());
        }
        if self.height.is_none() {
            self.height = Some(HashMap::new());
            for re in self.stack.clone() {
                self.check_height(re)?;
            }
        }
        if self.calc_height(ix, true) > MAX_HEIGHT {
            return Err(Fail::Nesting);
        }
        Ok(())
    }

    fn calc_height(&mut self, ix: usize, force: bool) -> i32 {
        if !force && let Some(&h) = self.height.as_ref().and_then(|m| m.get(&ix)) {
            return h;
        }
        let mut h = 1;
        for sub in self.nodes[ix].sub.clone() {
            h = h.max(1 + self.calc_height(sub, false));
        }
        if let Some(m) = &mut self.height {
            m.insert(ix, h);
        }
        h
    }

    /// Go `push`. `None` when the node was folded into the literal below.
    fn push(&mut self, ix: usize) -> Res<Option<usize>> {
        self.num_runes += self.nodes[ix].rune.len() as i64;
        let re = &self.nodes[ix];
        let r = &re.rune;
        if re.op == Op::CharClass && r.len() == 2 && r[0] == r[1] {
            let r0 = r[0];
            if self.maybe_concat(r0, self.flags & !FOLD_CASE) {
                return Ok(None);
            }
            let flags = self.flags & !FOLD_CASE;
            let re = &mut self.nodes[ix];
            re.op = Op::Literal;
            re.rune.truncate(1);
            re.flags = flags;
        } else if re.op == Op::CharClass
            && ((r.len() == 4
                && r[0] == r[1]
                && r[2] == r[3]
                && simple_fold(r[0]) == r[2]
                && simple_fold(r[2]) == r[0])
                || (r.len() == 2
                    && r[0] + 1 == r[1]
                    && simple_fold(r[0]) == r[1]
                    && simple_fold(r[1]) == r[0]))
        {
            let r0 = r[0];
            if self.maybe_concat(r0, self.flags | FOLD_CASE) {
                return Ok(None);
            }
            let flags = self.flags | FOLD_CASE;
            let re = &mut self.nodes[ix];
            re.op = Op::Literal;
            re.rune.truncate(1);
            re.flags = flags;
        } else {
            self.maybe_concat(-1, 0);
        }
        self.stack.push(ix);
        self.check_limits(ix)?;
        Ok(Some(ix))
    }

    /// Go `maybeConcat`: merges the top two literals; with `r >= 0`,
    /// reuses the freed node for `r` and reports true.
    fn maybe_concat(&mut self, r: i32, flags: u16) -> bool {
        let n = self.stack.len();
        if n < 2 {
            return false;
        }
        let (i1, i2) = (self.stack[n - 1], self.stack[n - 2]);
        let (re1, re2) = (&self.nodes[i1], &self.nodes[i2]);
        if re1.op != Op::Literal
            || re2.op != Op::Literal
            || re1.flags & FOLD_CASE != re2.flags & FOLD_CASE
        {
            return false;
        }
        let runes = re1.rune.clone();
        self.nodes[i2].rune.extend(runes);
        if r >= 0 {
            let re1 = &mut self.nodes[i1];
            re1.rune = vec![r];
            re1.flags = flags;
            return true;
        }
        self.stack.truncate(n - 1);
        self.reuse(i1);
        false
    }

    /// Go `literal`.
    fn literal(&mut self, mut r: i32) -> Res<()> {
        let ix = self.new_regexp(Op::Literal);
        self.nodes[ix].flags = self.flags;
        if self.flags & FOLD_CASE != 0 {
            r = min_fold_rune(r);
        }
        self.nodes[ix].rune = vec![r];
        self.push(ix)?;
        Ok(())
    }

    /// Go `op`.
    fn op(&mut self, op: Op) -> Res<Option<usize>> {
        let ix = self.new_regexp(op);
        self.nodes[ix].flags = self.flags;
        self.push(ix)
    }

    /// Go `repeat`. `before` is where the operator starts, `after` where
    /// it ends; returns the new `after`.
    fn repeat(
        &mut self,
        op: Op,
        min: i32,
        max: i32,
        before: usize,
        mut after: usize,
        last_repeat: Option<usize>,
    ) -> Res<usize> {
        let mut flags = self.flags;
        if self.flags & PERL_X != 0 {
            if self.at(after) == Some(b'?') {
                after += 1;
                flags ^= NON_GREEDY;
            }
            if let Some(last) = last_repeat {
                return self.syntax(ERR_INVALID_REPEAT_OP, last, after);
            }
        }
        let n = self.stack.len();
        if n == 0 || self.nodes[self.stack[n - 1]].op >= Op::LeftParen {
            return self.syntax(ERR_MISSING_REPEAT_ARGUMENT, before, after);
        }
        let sub = self.stack[n - 1];
        let ix = self.new_regexp(op);
        let re = &mut self.nodes[ix];
        re.min = min;
        re.max = max;
        re.flags = flags;
        re.sub = vec![sub];
        self.stack[n - 1] = ix;
        self.check_limits(ix)?;
        if op == Op::Repeat && (min >= 2 || max >= 2) && !self.repeat_is_valid(ix, 1000) {
            return self.syntax(ERR_INVALID_REPEAT_SIZE, before, after);
        }
        Ok(after)
    }

    /// Go `repeatIsValid`.
    fn repeat_is_valid(&self, ix: usize, mut n: i32) -> bool {
        let re = &self.nodes[ix];
        if re.op == Op::Repeat {
            let mut m = re.max;
            if m == 0 {
                return true;
            }
            if m < 0 {
                m = re.min;
            }
            if m > n {
                return false;
            }
            if m > 0 {
                n /= m;
            }
        }
        re.sub.iter().all(|&s| self.repeat_is_valid(s, n))
    }

    /// The stack index above the topmost pseudo-op.
    fn above_pseudo(&self) -> usize {
        let mut i = self.stack.len();
        while i > 0 && self.nodes[self.stack[i - 1]].op < Op::LeftParen {
            i -= 1;
        }
        i
    }

    /// Go `concat`.
    fn concat(&mut self) -> Res<Option<usize>> {
        self.maybe_concat(-1, 0);
        let i = self.above_pseudo();
        let subs = self.stack.split_off(i);
        if subs.is_empty() {
            let e = self.new_regexp(Op::EmptyMatch);
            return self.push(e);
        }
        let re = self.collapse(subs, Op::Concat)?;
        self.push(re)
    }

    /// Go `alternate`.
    fn alternate(&mut self) -> Res<Option<usize>> {
        let i = self.above_pseudo();
        let subs = self.stack.split_off(i);
        if let Some(&last) = subs.last() {
            self.clean_alt(last);
        }
        if subs.is_empty() {
            let e = self.new_regexp(Op::NoMatch);
            return self.push(e);
        }
        let re = self.collapse(subs, Op::Alternate)?;
        self.push(re)
    }

    /// Go `cleanAlt`.
    fn clean_alt(&mut self, ix: usize) {
        let re = &mut self.nodes[ix];
        if re.op == Op::CharClass {
            clean_class(&mut re.rune);
            if re.rune == [0, MAX_RUNE] {
                re.rune.clear();
                re.op = Op::AnyChar;
            } else if re.rune == [0, 0x0a - 1, 0x0a + 1, MAX_RUNE] {
                re.rune.clear();
                re.op = Op::AnyCharNotNL;
            }
        }
    }

    /// Go `collapse`.
    fn collapse(&mut self, subs: Vec<usize>, op: Op) -> Res<usize> {
        if subs.len() == 1 {
            return Ok(subs[0]);
        }
        let ix = self.new_regexp(op);
        let mut list = Vec::with_capacity(subs.len());
        for sub in subs {
            if self.nodes[sub].op == op {
                list.extend(self.nodes[sub].sub.iter().copied());
                self.reuse(sub);
            } else {
                list.push(sub);
            }
        }
        let mut re = ix;
        if op == Op::Alternate {
            list = self.factor(list)?;
            if list.len() == 1 {
                let old = re;
                re = list[0];
                self.reuse(old);
                return Ok(re);
            }
        }
        self.nodes[re].sub = list;
        Ok(re)
    }

    /// Go `leadingString`: the leading literal and its fold flag.
    fn leading_string(&self, ix: usize) -> (Vec<i32>, u16) {
        let mut re = &self.nodes[ix];
        if re.op == Op::Concat && !re.sub.is_empty() {
            re = &self.nodes[re.sub[0]];
        }
        if re.op != Op::Literal {
            return (Vec::new(), 0);
        }
        (re.rune.clone(), re.flags & FOLD_CASE)
    }

    /// Go `removeLeadingString`.
    fn remove_leading_string(&mut self, ix: usize, n: usize) -> usize {
        let re = &self.nodes[ix];
        if re.op == Op::Concat && !re.sub.is_empty() {
            let sub = self.remove_leading_string(re.sub[0], n);
            self.nodes[ix].sub[0] = sub;
            if self.nodes[sub].op == Op::EmptyMatch {
                self.reuse(sub);
                match self.nodes[ix].sub.len() {
                    0 | 1 => {
                        let re = &mut self.nodes[ix];
                        re.op = Op::EmptyMatch;
                        re.sub.clear();
                    }
                    2 => {
                        let old = ix;
                        let next = self.nodes[ix].sub[1];
                        self.reuse(old);
                        return next;
                    }
                    _ => {
                        self.nodes[ix].sub.remove(0);
                    }
                }
            }
            return ix;
        }
        if re.op == Op::Literal {
            let re = &mut self.nodes[ix];
            re.rune.drain(..n.min(re.rune.len()));
            if re.rune.is_empty() {
                re.op = Op::EmptyMatch;
            }
        }
        ix
    }

    /// Go `leadingRegexp`.
    fn leading_regexp(&self, ix: usize) -> Option<usize> {
        let re = &self.nodes[ix];
        if re.op == Op::EmptyMatch {
            return None;
        }
        if re.op == Op::Concat && !re.sub.is_empty() {
            let sub = re.sub[0];
            if self.nodes[sub].op == Op::EmptyMatch {
                return None;
            }
            return Some(sub);
        }
        Some(ix)
    }

    /// Go `removeLeadingRegexp`.
    fn remove_leading_regexp(&mut self, ix: usize, reuse: bool) -> usize {
        let re = &self.nodes[ix];
        if re.op == Op::Concat && !re.sub.is_empty() {
            if reuse {
                self.reuse(re.sub[0]);
            }
            self.nodes[ix].sub.remove(0);
            match self.nodes[ix].sub.len() {
                0 => {
                    let re = &mut self.nodes[ix];
                    re.op = Op::EmptyMatch;
                    re.sub.clear();
                }
                1 => {
                    let next = self.nodes[ix].sub[0];
                    self.reuse(ix);
                    return next;
                }
                _ => {}
            }
            return ix;
        }
        if reuse {
            self.reuse(ix);
        }
        self.new_regexp(Op::EmptyMatch)
    }

    /// Go `Regexp.Equal`.
    fn equal(&self, x: usize, y: usize) -> bool {
        let (a, b) = (&self.nodes[x], &self.nodes[y]);
        if a.op != b.op {
            return false;
        }
        match a.op {
            Op::EndText => a.flags & WAS_DOLLAR == b.flags & WAS_DOLLAR,
            Op::Literal | Op::CharClass => {
                a.flags & FOLD_CASE == b.flags & FOLD_CASE && a.rune == b.rune
            }
            Op::Alternate | Op::Concat => {
                a.sub.len() == b.sub.len()
                    && a.sub.iter().zip(&b.sub).all(|(&p, &q)| self.equal(p, q))
            }
            Op::Star | Op::Plus | Op::Quest => {
                a.flags & NON_GREEDY == b.flags & NON_GREEDY && self.equal(a.sub[0], b.sub[0])
            }
            Op::Repeat => {
                a.flags & NON_GREEDY == b.flags & NON_GREEDY
                    && a.min == b.min
                    && a.max == b.max
                    && self.equal(a.sub[0], b.sub[0])
            }
            Op::Capture => a.cap == b.cap && a.name == b.name && self.equal(a.sub[0], b.sub[0]),
            _ => true,
        }
    }

    /// Go `isCharClass`.
    fn is_char_class(&self, ix: usize) -> bool {
        let re = &self.nodes[ix];
        (re.op == Op::Literal && re.rune.len() == 1)
            || matches!(re.op, Op::CharClass | Op::AnyCharNotNL | Op::AnyChar)
    }

    /// Go `matchRune`.
    fn match_rune(&self, ix: usize, r: i32) -> bool {
        let re = &self.nodes[ix];
        match re.op {
            Op::Literal => re.rune.len() == 1 && re.rune[0] == r,
            Op::CharClass => re.rune.chunks_exact(2).any(|p| p[0] <= r && r <= p[1]),
            Op::AnyCharNotNL => r != 0x0a,
            Op::AnyChar => true,
            _ => false,
        }
    }

    /// Go `mergeCharClass`.
    fn merge_char_class(&mut self, dst: usize, src: usize) {
        match self.nodes[dst].op {
            Op::AnyCharNotNL => {
                if self.match_rune(src, 0x0a) {
                    self.nodes[dst].op = Op::AnyChar;
                }
            }
            Op::CharClass => {
                let s = self.nodes[src].clone();
                let d = &mut self.nodes[dst].rune;
                if s.op == Op::Literal {
                    append_literal(d, s.rune[0], s.flags);
                } else {
                    append_class(d, &s.rune);
                }
            }
            Op::Literal => {
                let (sr, sf) = (self.nodes[src].rune[0], self.nodes[src].flags);
                let d = &mut self.nodes[dst];
                if sr == d.rune[0] && sf == d.flags {
                    return;
                }
                let (dr, df) = (d.rune[0], d.flags);
                d.op = Op::CharClass;
                d.rune.clear();
                append_literal(&mut d.rune, dr, df);
                append_literal(&mut d.rune, sr, sf);
            }
            _ => {}
        }
    }

    /// Go `factor`: factors common prefixes out of an alternation.
    fn factor(&mut self, mut sub: Vec<usize>) -> Res<Vec<usize>> {
        if sub.len() < 2 {
            return Ok(sub);
        }

        // Round 1: common literal prefixes.
        let mut out = Vec::with_capacity(sub.len());
        let mut s: Vec<i32> = Vec::new();
        let mut sflags = 0;
        let mut start = 0;
        for i in 0..=sub.len() {
            let mut istr = Vec::new();
            let mut iflags = 0;
            if i < sub.len() {
                (istr, iflags) = self.leading_string(sub[i]);
                if iflags == sflags {
                    let same = s.iter().zip(&istr).take_while(|(a, b)| a == b).count();
                    if same > 0 {
                        s.truncate(same);
                        continue;
                    }
                }
            }
            if i == start {
            } else if i == start + 1 {
                out.push(sub[start]);
            } else {
                let prefix = self.new_regexp(Op::Literal);
                self.nodes[prefix].flags = sflags;
                self.nodes[prefix].rune = s.clone();
                for slot in &mut sub[start..i] {
                    *slot = self.remove_leading_string(*slot, s.len());
                    self.check_limits(*slot)?;
                }
                let suffix = self.collapse(sub[start..i].to_vec(), Op::Alternate)?;
                let re = self.new_regexp(Op::Concat);
                self.nodes[re].sub = vec![prefix, suffix];
                out.push(re);
            }
            start = i;
            s = istr;
            sflags = iflags;
        }
        sub = out;

        // Round 2: a common leading character class (or fixed repeat of
        // one).
        let mut out = Vec::with_capacity(sub.len());
        let mut start = 0;
        let mut first: Option<usize> = None;
        for i in 0..=sub.len() {
            let mut ifirst = None;
            if i < sub.len() {
                ifirst = self.leading_regexp(sub[i]);
                if let (Some(f), Some(fi)) = (first, ifirst)
                    && self.equal(f, fi)
                    && (self.is_char_class(f) || {
                        let fr = &self.nodes[f];
                        fr.op == Op::Repeat && fr.min == fr.max && self.is_char_class(fr.sub[0])
                    })
                {
                    continue;
                }
            }
            if i == start {
            } else if i == start + 1 {
                out.push(sub[start]);
            } else {
                // `first` is set: the run has two or more members.
                let prefix = first.unwrap_or(sub[start]);
                for (k, slot) in sub[start..i].iter_mut().enumerate() {
                    // The first member's leading regexp is the prefix.
                    *slot = self.remove_leading_regexp(*slot, k != 0);
                    self.check_limits(*slot)?;
                }
                let suffix = self.collapse(sub[start..i].to_vec(), Op::Alternate)?;
                let re = self.new_regexp(Op::Concat);
                self.nodes[re].sub = vec![prefix, suffix];
                out.push(re);
            }
            start = i;
            first = ifirst;
        }
        sub = out;

        // Round 3: runs of single characters and classes become one class.
        let mut out = Vec::with_capacity(sub.len());
        let mut start = 0;
        for i in 0..=sub.len() {
            if i < sub.len() && self.is_char_class(sub[i]) {
                continue;
            }
            if i == start {
            } else if i == start + 1 {
                out.push(sub[start]);
            } else {
                let mut max = start;
                for j in start + 1..i {
                    let (m, n) = (&self.nodes[sub[max]], &self.nodes[sub[j]]);
                    if m.op < n.op || (m.op == n.op && m.rune.len() < n.rune.len()) {
                        max = j;
                    }
                }
                sub.swap(start, max);
                for j in start + 1..i {
                    self.merge_char_class(sub[start], sub[j]);
                    self.reuse(sub[j]);
                }
                self.clean_alt(sub[start]);
                out.push(sub[start]);
            }
            if i < sub.len() {
                out.push(sub[i]);
            }
            start = i + 1;
        }
        sub = out;

        // Round 4: runs of empty matches become one.
        let mut out = Vec::with_capacity(sub.len());
        for i in 0..sub.len() {
            if i + 1 < sub.len()
                && self.nodes[sub[i]].op == Op::EmptyMatch
                && self.nodes[sub[i + 1]].op == Op::EmptyMatch
            {
                continue;
            }
            out.push(sub[i]);
        }
        Ok(out)
    }

    /// Go `swapVerticalBar`.
    fn swap_vertical_bar(&mut self) -> bool {
        let n = self.stack.len();
        if n >= 3
            && self.nodes[self.stack[n - 2]].op == Op::VerticalBar
            && self.is_char_class(self.stack[n - 1])
            && self.is_char_class(self.stack[n - 3])
        {
            let mut re1 = self.stack[n - 1];
            let mut re3 = self.stack[n - 3];
            if self.nodes[re1].op > self.nodes[re3].op {
                std::mem::swap(&mut re1, &mut re3);
                self.stack[n - 3] = re3;
            }
            self.merge_char_class(re3, re1);
            self.reuse(re1);
            self.stack.truncate(n - 1);
            return true;
        }
        if n >= 2 {
            let re1 = self.stack[n - 1];
            let re2 = self.stack[n - 2];
            if self.nodes[re2].op == Op::VerticalBar {
                if n >= 3 {
                    self.clean_alt(self.stack[n - 3]);
                }
                self.stack[n - 2] = re1;
                self.stack[n - 1] = re2;
                return true;
            }
        }
        false
    }

    /// Go `parseVerticalBar`.
    fn parse_vertical_bar(&mut self) -> Res<()> {
        self.concat()?;
        if !self.swap_vertical_bar() {
            self.op(Op::VerticalBar)?;
        }
        Ok(())
    }

    /// Go `parseRightParen`.
    fn parse_right_paren(&mut self) -> Res<()> {
        self.concat()?;
        if self.swap_vertical_bar() {
            self.stack.pop();
        }
        self.alternate()?;
        let n = self.stack.len();
        if n < 2 {
            return self.syntax(ERR_UNEXPECTED_PAREN, 0, self.s.len());
        }
        let re1 = self.stack[n - 1];
        let re2 = self.stack[n - 2];
        self.stack.truncate(n - 2);
        if self.nodes[re2].op != Op::LeftParen {
            return self.syntax(ERR_UNEXPECTED_PAREN, 0, self.s.len());
        }
        self.flags = self.nodes[re2].flags;
        if self.nodes[re2].cap == 0 {
            self.push(re1)?;
        } else {
            let re = &mut self.nodes[re2];
            re.op = Op::Capture;
            re.sub = vec![re1];
            self.push(re2)?;
        }
        Ok(())
    }

    /// Go `parseRepeat` at `pos` (a `{`): `(min, max, after)`. `max` is -1
    /// for `{n,}`; `min` is -1 when a number is too big.
    fn parse_repeat(&self, pos: usize) -> Option<(i32, i32, usize)> {
        let b = self.b();
        if b.get(pos) != Some(&b'{') {
            return None;
        }
        let (mut min, mut i) = parse_int(b, pos + 1)?;
        let max;
        match b.get(i)? {
            b',' => {
                i += 1;
                if *b.get(i)? == b'}' {
                    max = -1;
                } else {
                    let (m, j) = parse_int(b, i)?;
                    i = j;
                    max = m;
                    if max < 0 {
                        min = -1;
                    }
                }
            }
            _ => max = min,
        }
        if b.get(i) != Some(&b'}') {
            return None;
        }
        Some((min, max, i + 1))
    }

    /// Go `parsePerlFlags` at `pos` (a `(?`); returns the position after.
    fn parse_perl_flags(&mut self, pos: usize) -> Res<usize> {
        let b = self.b();
        let rest = b.len() - pos;
        let starts_with_p = rest > 4 && b[pos + 2] == b'P' && b[pos + 3] == b'<';
        let starts_with_name = rest > 3 && b[pos + 2] == b'<';
        if starts_with_p || starts_with_name {
            let expr_start = pos + if starts_with_name { 3 } else { 4 };
            let Some(end) = b[pos..].iter().position(|&c| c == b'>') else {
                return self.syntax(ERR_INVALID_NAMED_CAPTURE, pos, b.len());
            };
            let end = pos + end;
            let name = &self.s[expr_start..end];
            if name.is_empty() || !name.bytes().all(|c| c == b'_' || is_alnum(i32::from(c))) {
                return self.syntax(ERR_INVALID_NAMED_CAPTURE, pos, end + 1);
            }
            self.num_cap += 1;
            let cap = self.num_cap;
            if let Some(re) = self.op(Op::LeftParen)? {
                self.nodes[re].cap = cap;
                self.nodes[re].name = name.to_string();
            }
            return Ok(end + 1);
        }

        let mut t = pos + 2;
        let mut flags = self.flags;
        let mut sign = 1;
        let mut saw_flag = false;
        while t < b.len() {
            let (c, next) = self.next_rune(t);
            t = next;
            match u8::try_from(c).unwrap_or(0) {
                b'i' => {
                    flags |= FOLD_CASE;
                    saw_flag = true;
                }
                b'm' => {
                    flags &= !ONE_LINE;
                    saw_flag = true;
                }
                b's' => {
                    flags |= DOT_NL;
                    saw_flag = true;
                }
                b'U' => {
                    flags |= NON_GREEDY;
                    saw_flag = true;
                }
                b'-' => {
                    if sign < 0 {
                        break;
                    }
                    sign = -1;
                    flags = !flags;
                    saw_flag = false;
                }
                c @ (b':' | b')') => {
                    if sign < 0 {
                        if !saw_flag {
                            break;
                        }
                        flags = !flags;
                    }
                    if c == b':' {
                        self.op(Op::LeftParen)?;
                    }
                    self.flags = flags;
                    return Ok(t);
                }
                _ => break,
            }
        }
        self.syntax(ERR_INVALID_PERL_OP, pos, t)
    }

    /// Go `parseEscape` at `pos` (a `\`): `(rune, after)`.
    fn parse_escape(&self, pos: usize) -> Res<(i32, usize)> {
        let b = self.b();
        let mut t = pos + 1;
        if t >= b.len() {
            return Err(Fail::Syntax(ERR_TRAILING_BACKSLASH, String::new()));
        }
        let (c, next) = self.next_rune(t);
        t = next;
        let octal = |t: usize| b.get(t).is_some_and(|d| (b'0'..=b'7').contains(d));
        match c {
            0x31..=0x37 if !octal(t) => {}
            0x30..=0x37 => {
                let mut r = c - 0x30;
                for _ in 1..3 {
                    if !octal(t) {
                        break;
                    }
                    r = r * 8 + i32::from(b[t] - b'0');
                    t += 1;
                }
                return Ok((r, t));
            }
            0x78 /* x */ => 'x: {
                if t >= b.len() {
                    break 'x;
                }
                let (c, next) = self.next_rune(t);
                t = next;
                if c == i32::from(b'{') {
                    let mut nhex = 0;
                    let mut r: i32 = 0;
                    loop {
                        if t >= b.len() {
                            break 'x;
                        }
                        let (c, next) = self.next_rune(t);
                        t = next;
                        if c == i32::from(b'}') {
                            break;
                        }
                        let v = unhex(c);
                        if v < 0 {
                            break 'x;
                        }
                        r = r * 16 + v;
                        if r > MAX_RUNE {
                            break 'x;
                        }
                        nhex += 1;
                    }
                    if nhex == 0 {
                        break 'x;
                    }
                    return Ok((r, t));
                }
                let x = unhex(c);
                let (c, next) = self.next_rune(t);
                t = next;
                let y = unhex(c);
                if x < 0 || y < 0 {
                    break 'x;
                }
                return Ok((x * 16 + y, t));
            }
            0x61 => return Ok((0x07, t)),
            0x66 => return Ok((0x0c, t)),
            0x6e => return Ok((0x0a, t)),
            0x72 => return Ok((0x0d, t)),
            0x74 => return Ok((0x09, t)),
            0x76 => return Ok((0x0b, t)),
            _ if c < 0x80 && !is_alnum(c) => return Ok((c, t)),
            _ => {}
        }
        self.syntax(ERR_INVALID_ESCAPE, pos, t)
    }

    /// Go `parseClassChar`; `whole` is where the class starts.
    fn parse_class_char(&self, pos: usize, whole: usize) -> Res<(i32, usize)> {
        if pos >= self.s.len() {
            return self.syntax(ERR_MISSING_BRACKET, whole, self.s.len());
        }
        if self.b()[pos] == b'\\' {
            return self.parse_escape(pos);
        }
        Ok(self.next_rune(pos))
    }

    /// Go `appendGroup`.
    fn append_group(&self, r: &mut Vec<i32>, sign: i32, class: &[i32]) {
        if self.flags & FOLD_CASE == 0 {
            if sign < 0 {
                append_negated_class(r, class);
            } else {
                append_class(r, class);
            }
        } else {
            let mut tmp = Vec::new();
            append_folded_class(&mut tmp, class);
            clean_class(&mut tmp);
            if sign < 0 {
                append_negated_class(r, &tmp);
            } else {
                append_class(r, &tmp);
            }
        }
    }

    /// Go `parsePerlClassEscape`: appends to `r` and returns the position
    /// after, or `None`.
    fn parse_perl_class_escape(&self, pos: usize, r: &mut Vec<i32>) -> Option<usize> {
        if self.flags & PERL_X == 0 || self.b().get(pos) != Some(&b'\\') {
            return None;
        }
        let (sign, class) = perl_group(self.b().get(pos..pos + 2)?)?;
        self.append_group(r, sign, class);
        Some(pos + 2)
    }

    /// Go `parseNamedClass` (`[:alpha:]`).
    fn parse_named_class(&self, pos: usize, r: &mut Vec<i32>) -> Res<Option<usize>> {
        let b = self.b();
        if b.get(pos) != Some(&b'[') || b.get(pos + 1) != Some(&b':') {
            return Ok(None);
        }
        let Some(i) = b[pos + 2..].windows(2).position(|w| w == b":]") else {
            return Ok(None);
        };
        let end = pos + 2 + i + 2;
        let Some((sign, class)) = posix_group(&b[pos..end]) else {
            return self.syntax(ERR_INVALID_CHAR_RANGE, pos, end);
        };
        self.append_group(r, sign, class);
        Ok(Some(end))
    }

    /// Go `parseUnicodeClass` (`\pL`, `\p{Greek}`, `\P{^L}`).
    fn parse_unicode_class(&self, pos: usize, r: &mut Vec<i32>) -> Res<Option<usize>> {
        let b = self.b();
        if self.flags & UNICODE_GROUPS == 0
            || b.get(pos) != Some(&b'\\')
            || !matches!(b.get(pos + 1), Some(b'p' | b'P'))
        {
            return Ok(None);
        }
        let mut sign = if b[pos + 1] == b'P' { -1 } else { 1 };
        let (c, mut t) = self.next_rune(pos + 2);
        let (seq_end, name) = if c != i32::from(b'{') {
            (t, &b[pos + 2..t])
        } else {
            let Some(end) = b[pos..].iter().position(|&c| c == b'}') else {
                return self.syntax(ERR_INVALID_CHAR_RANGE, pos, b.len());
            };
            let end = pos + end;
            t = end + 1;
            (end + 1, &b[pos + 3..end])
        };
        let mut name = name;
        if let Some(rest) = name.strip_prefix(b"^") {
            sign = -sign;
            name = rest;
        }
        let Some((tab, fold, tsign)) = unicode_table(name) else {
            return self.syntax(ERR_INVALID_CHAR_RANGE, pos, seq_end);
        };
        if tsign < 0 {
            sign = -sign;
        }
        match fold {
            Table::Runs(fold) if self.flags & FOLD_CASE != 0 => {
                let mut tmp = Vec::new();
                append_table(&mut tmp, tab);
                append_table(&mut tmp, fold);
                clean_class(&mut tmp);
                if sign > 0 {
                    append_class(r, &tmp);
                } else {
                    append_negated_class(r, &tmp);
                }
            }
            _ => {
                if sign > 0 {
                    append_table(r, tab);
                } else {
                    append_negated_table(r, tab);
                }
            }
        }
        Ok(Some(t))
    }

    /// Go `parseClass` at `pos` (a `[`).
    fn parse_class(&mut self, pos: usize) -> Res<usize> {
        let b = self.b();
        let mut t = pos + 1;
        let ix = self.new_regexp(Op::CharClass);
        self.nodes[ix].flags = self.flags;
        let mut sign = 1;
        if b.get(t) == Some(&b'^') {
            sign = -1;
            t += 1;
            // Perl flags include ClassNL: a negated class may match \n.
        }
        let mut class = Vec::new();
        let mut first = true;
        while t >= b.len() || b[t] != b']' || first {
            first = false;
            if b.len() - t.min(b.len()) > 2
                && b[t] == b'['
                && b[t + 1] == b':'
                && let Some(nt) = self.parse_named_class(t, &mut class)?
            {
                t = nt;
                continue;
            }
            if let Some(nt) = self.parse_unicode_class(t, &mut class)? {
                t = nt;
                continue;
            }
            if let Some(nt) = self.parse_perl_class_escape(t, &mut class) {
                t = nt;
                continue;
            }
            let rng = t;
            let (lo, nt) = self.parse_class_char(t, pos)?;
            t = nt;
            let mut hi = lo;
            if b.get(t) == Some(&b'-') && b.get(t + 1).is_some_and(|&c| c != b']') {
                let (h, nt) = self.parse_class_char(t + 1, pos)?;
                t = nt;
                hi = h;
                if hi < lo {
                    return self.syntax(ERR_INVALID_CHAR_RANGE, rng, t);
                }
            }
            if self.flags & FOLD_CASE == 0 {
                append_range(&mut class, lo, hi);
            } else {
                append_folded_range(&mut class, lo, hi);
            }
        }
        t += 1;
        clean_class(&mut class);
        if sign < 0 {
            negate_class(&mut class);
        }
        self.nodes[ix].rune = class;
        self.push(ix)?;
        Ok(t)
    }

    /// Go `parse` with the Perl flags.
    fn parse(&mut self) -> Res<usize> {
        let b = self.b();
        let mut t = 0;
        let mut last_repeat: Option<usize> = None;
        while t < b.len() {
            let mut repeat = None;
            match b[t] {
                b'(' => {
                    if self.flags & PERL_X != 0 && b.get(t + 1) == Some(&b'?') {
                        t = self.parse_perl_flags(t)?;
                    } else {
                        self.num_cap += 1;
                        let cap = self.num_cap;
                        if let Some(re) = self.op(Op::LeftParen)? {
                            self.nodes[re].cap = cap;
                        }
                        t += 1;
                    }
                }
                b'|' => {
                    self.parse_vertical_bar()?;
                    t += 1;
                }
                b')' => {
                    self.parse_right_paren()?;
                    t += 1;
                }
                b'^' => {
                    self.op(if self.flags & ONE_LINE != 0 {
                        Op::BeginText
                    } else {
                        Op::BeginLine
                    })?;
                    t += 1;
                }
                b'$' => {
                    if self.flags & ONE_LINE != 0 {
                        if let Some(re) = self.op(Op::EndText)? {
                            self.nodes[re].flags |= WAS_DOLLAR;
                        }
                    } else {
                        self.op(Op::EndLine)?;
                    }
                    t += 1;
                }
                b'.' => {
                    self.op(if self.flags & DOT_NL != 0 {
                        Op::AnyChar
                    } else {
                        Op::AnyCharNotNL
                    })?;
                    t += 1;
                }
                b'[' => t = self.parse_class(t)?,
                c @ (b'*' | b'+' | b'?') => {
                    let op = match c {
                        b'*' => Op::Star,
                        b'+' => Op::Plus,
                        _ => Op::Quest,
                    };
                    let before = t;
                    t = self.repeat(op, 0, 0, before, t + 1, last_repeat)?;
                    repeat = Some(before);
                }
                b'{' => {
                    let before = t;
                    match self.parse_repeat(t) {
                        None => {
                            self.literal(i32::from(b'{'))?;
                            t += 1;
                        }
                        Some((min, max, after)) => {
                            if !(0..=1000).contains(&min) || max > 1000 || (max >= 0 && min > max) {
                                return self.syntax(ERR_INVALID_REPEAT_SIZE, before, after);
                            }
                            t = self.repeat(Op::Repeat, min, max, before, after, last_repeat)?;
                            repeat = Some(before);
                        }
                    }
                }
                b'\\' => t = self.parse_backslash(t)?,
                _ => {
                    let (c, next) = self.next_rune(t);
                    self.literal(c)?;
                    t = next;
                }
            }
            last_repeat = repeat;
        }

        self.concat()?;
        if self.swap_vertical_bar() {
            self.stack.pop();
        }
        self.alternate()?;
        if self.stack.len() != 1 {
            return self.syntax(ERR_MISSING_PAREN, 0, self.s.len());
        }
        Ok(self.stack[0])
    }

    /// The `\` case of Go's `parse` loop.
    fn parse_backslash(&mut self, t: usize) -> Res<usize> {
        let b = self.b();
        if self.flags & PERL_X != 0 && t + 1 < b.len() {
            match b[t + 1] {
                b'A' => {
                    self.op(Op::BeginText)?;
                    return Ok(t + 2);
                }
                b'b' => {
                    self.op(Op::WordBoundary)?;
                    return Ok(t + 2);
                }
                b'B' => {
                    self.op(Op::NoWordBoundary)?;
                    return Ok(t + 2);
                }
                b'C' => return self.syntax(ERR_INVALID_ESCAPE, t, t + 2),
                b'Q' => {
                    let body = t + 2;
                    let (lit_end, after) = match self.s[body..].find("\\E") {
                        Some(i) => (body + i, body + i + 2),
                        None => (b.len(), b.len()),
                    };
                    let mut p = body;
                    while p < lit_end {
                        let (c, next) = self.next_rune(p);
                        self.literal(c)?;
                        p = next;
                    }
                    return Ok(after);
                }
                b'z' => {
                    self.op(Op::EndText)?;
                    return Ok(t + 2);
                }
                _ => {}
            }
        }

        let ix = self.new_regexp(Op::CharClass);
        self.nodes[ix].flags = self.flags;

        let mut class = Vec::new();
        if b.get(t + 1).is_some_and(|&c| c == b'p' || c == b'P')
            && let Some(rest) = self.parse_unicode_class(t, &mut class)?
        {
            self.nodes[ix].rune = class;
            self.push(ix)?;
            return Ok(rest);
        }
        if let Some(rest) = self.parse_perl_class_escape(t, &mut class) {
            self.nodes[ix].rune = class;
            self.push(ix)?;
            return Ok(rest);
        }
        self.reuse(ix);

        let (c, rest) = self.parse_escape(t)?;
        self.literal(c)?;
        Ok(rest)
    }
}

/// Go `syntax.Parse(pat, syntax.Perl)`: the arena and the root, or Go's
/// error text.
fn parse(pat: &str) -> Result<(Vec<Node>, usize), String> {
    let mut p = Parser {
        s: pat,
        flags: PERL,
        stack: Vec::new(),
        nodes: Vec::new(),
        free: Vec::new(),
        num_cap: 0,
        num_regexp: 0,
        num_runes: 0,
        repeats: 0,
        height: None,
        size: None,
    };
    match p.parse() {
        Ok(root) => Ok((p.nodes, root)),
        Err(Fail::Syntax(code, expr)) => Err(go_error(code, &expr)),
        Err(Fail::Large) => Err(go_error(ERR_LARGE, pat)),
        Err(Fail::Nesting) => Err(go_error(ERR_NESTING_DEPTH, pat)),
    }
}

/// Go `syntax.Error.Error()`.
fn go_error(code: &str, expr: &str) -> String {
    format!("error parsing regexp: {code}: `{expr}`")
}

