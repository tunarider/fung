/// A class of Go rune pairs; surrogates (never in a `&str`) are dropped.
fn class_hir(pairs: &[i32]) -> Hir {
    let mut ranges = Vec::new();
    let mut add = |lo: i32, hi: i32| {
        if let (Some(lo), Some(hi)) = (
            char::from_u32(lo.max(0) as u32),
            char::from_u32(hi.min(MAX_RUNE) as u32),
        ) && lo <= hi
        {
            ranges.push(hir::ClassUnicodeRange::new(lo, hi));
        }
    };
    for p in pairs.chunks_exact(2) {
        let (lo, hi) = (p[0], p[1]);
        if hi < 0xD800 || lo > 0xDFFF {
            add(lo, hi);
        } else {
            if lo < 0xD800 {
                add(lo, 0xD7FF);
            }
            if hi > 0xDFFF {
                add(0xE000, hi);
            }
        }
    }
    Hir::class(hir::Class::Unicode(hir::ClassUnicode::new(ranges)))
}

/// One literal rune; case-insensitive means its whole fold orbit.
fn rune_hir(r: i32, fold: bool) -> Hir {
    if fold {
        let mut pairs = Vec::new();
        append_folded_range(&mut pairs, r, r);
        clean_class(&mut pairs);
        return class_hir(&pairs);
    }
    match u32::try_from(r).ok().and_then(char::from_u32) {
        Some(c) => Hir::literal(c.encode_utf8(&mut [0; 4]).as_bytes()),
        None => Hir::fail(),
    }
}

/// The Rust name of a Go capture group: unique and valid in Rust.
fn rust_capture_name(cap: i32, name: &str) -> String {
    format!("_{cap}_{name}")
}

fn has_capture(nodes: &[Node], ix: usize) -> bool {
    nodes[ix].op == Op::Capture || nodes[ix].sub.iter().any(|&s| has_capture(nodes, s))
}

fn to_hir(nodes: &[Node], ix: usize) -> Hir {
    let re = &nodes[ix];
    let rep = |min: u32, max: Option<u32>| {
        Hir::repetition(hir::Repetition {
            min,
            max,
            greedy: re.flags & NON_GREEDY == 0,
            sub: Box::new(to_hir(nodes, re.sub[0])),
        })
    };
    match re.op {
        Op::NoMatch | Op::LeftParen | Op::VerticalBar => Hir::fail(),
        Op::EmptyMatch => Hir::empty(),
        Op::Literal => Hir::concat(
            re.rune
                .iter()
                .map(|&r| rune_hir(r, re.flags & FOLD_CASE != 0))
                .collect(),
        ),
        Op::CharClass => class_hir(&re.rune),
        Op::AnyCharNotNL => class_hir(&[0, 0x09, 0x0b, MAX_RUNE]),
        Op::AnyChar => class_hir(&[0, MAX_RUNE]),
        Op::BeginLine => Hir::look(Look::StartLF),
        Op::EndLine => Hir::look(Look::EndLF),
        Op::BeginText => Hir::look(Look::Start),
        Op::EndText => Hir::look(Look::End),
        // Go's \b and \B are ASCII.
        Op::WordBoundary => Hir::look(Look::WordAscii),
        Op::NoWordBoundary => Hir::look(Look::WordAsciiNegate),
        Op::Capture => Hir::capture(hir::Capture {
            index: re.cap.unsigned_abs(),
            name: (!re.name.is_empty()).then(|| rust_capture_name(re.cap, &re.name).into()),
            sub: Box::new(to_hir(nodes, re.sub[0])),
        }),
        Op::Star => rep(0, None),
        Op::Plus => rep(1, None),
        Op::Quest => rep(0, Some(1)),
        Op::Repeat if re.max == 0 => {
            // `x{0}` matches the empty string, but Go still counts the
            // groups inside it; Rust's HIR would drop them. An
            // alternative that can never be taken keeps them.
            if has_capture(nodes, re.sub[0]) {
                Hir::alternation(vec![
                    Hir::empty(),
                    Hir::concat(vec![Hir::fail(), to_hir(nodes, re.sub[0])]),
                ])
            } else {
                Hir::empty()
            }
        }
        Op::Repeat => rep(re.min.unsigned_abs(), u32::try_from(re.max).ok()),
        Op::Concat => Hir::concat(re.sub.iter().map(|&s| to_hir(nodes, s)).collect()),
        Op::Alternate => Hir::alternation(re.sub.iter().map(|&s| to_hir(nodes, s)).collect()),
    }
}

/// A Go pattern as an equivalent pattern for the `regex` crate, or Go's
/// error text.
fn translate(pat: &str) -> Result<String, String> {
    let (nodes, root) = parse(pat)?;
    let hir = to_hir(&nodes, root);
    let mut src = String::new();
    print_hir(&hir, &mut src);
    // The engine must see exactly the tree built here.
    #[cfg(debug_assertions)]
    {
        let back = regex_syntax::ParserBuilder::new()
            .nest_limit(NEST_LIMIT)
            .build()
            .parse(&src);
        debug_assert!(
            back.as_ref() == Ok(&hir),
            "printed pattern {src:?} for {pat:?} parses to another tree"
        );
    }
    Ok(src)
}

/// Prints a HIR as a pattern for the `regex` crate. regex-syntax's own
/// printer writes a repetition of a repetition as `a{1,2}?`, which reads
/// back as one lazy repetition; here every repetition operand, literal
/// string, concatenation and alternation is wrapped in `(?:...)`, and
/// every character but ASCII letters and digits is written `\x{..}`, so
/// the text is unambiguous. `translate` checks the round trip in debug
/// builds.
fn print_hir(h: &Hir, out: &mut String) {
    use hir::HirKind;
    use std::fmt::Write;
    let ch = |c: char, out: &mut String| {
        if c.is_ascii_alphanumeric() {
            out.push(c);
        } else {
            let _ = write!(out, "\\x{{{:X}}}", u32::from(c));
        }
    };
    match h.kind() {
        HirKind::Empty => out.push_str("(?:)"),
        HirKind::Literal(hir::Literal(bytes)) => {
            out.push_str("(?:");
            // Literals are built from `char`s, so always UTF-8.
            for c in String::from_utf8_lossy(bytes).chars() {
                ch(c, out);
            }
            out.push(')');
        }
        HirKind::Class(hir::Class::Unicode(cls)) => {
            if cls.ranges().is_empty() {
                // Never matches.
                out.push_str("[a&&b]");
                return;
            }
            out.push('[');
            for r in cls.iter() {
                ch(r.start(), out);
                if r.end() != r.start() {
                    out.push('-');
                    ch(r.end(), out);
                }
            }
            out.push(']');
        }
        // Not built by `to_hir`.
        HirKind::Class(hir::Class::Bytes(_)) => out.push_str("[a&&b]"),
        HirKind::Look(look) => out.push_str(match look {
            Look::Start => "\\A",
            Look::End => "\\z",
            Look::StartLF => "(?m:^)",
            Look::EndLF => "(?m:$)",
            Look::WordAscii => "(?-u:\\b)",
            Look::WordAsciiNegate => "(?-u:\\B)",
            // Not built by `to_hir`.
            _ => "[a&&b]",
        }),
        HirKind::Repetition(rep) => {
            out.push_str("(?:");
            print_hir(&rep.sub, out);
            out.push(')');
            let _ = match (rep.min, rep.max) {
                (0, Some(1)) => write!(out, "?"),
                (0, None) => write!(out, "*"),
                (1, None) => write!(out, "+"),
                (m, None) => write!(out, "{{{m},}}"),
                (m, Some(n)) => write!(out, "{{{m},{n}}}"),
            };
            if !rep.greedy {
                out.push('?');
            }
        }
        HirKind::Capture(cap) => {
            out.push('(');
            if let Some(name) = &cap.name {
                let _ = write!(out, "?P<{name}>");
            }
            print_hir(&cap.sub, out);
            out.push(')');
        }
        HirKind::Concat(subs) => {
            out.push_str("(?:");
            for sub in subs {
                print_hir(sub, out);
            }
            out.push(')');
        }
        HirKind::Alternation(subs) => {
            out.push_str("(?:");
            for (i, sub) in subs.iter().enumerate() {
                if i > 0 {
                    out.push('|');
                }
                print_hir(sub, out);
            }
            out.push(')');
        }
    }
}

/// The Rust engine's compiled-size budget. Go limits its program to 128
/// MB of instructions; the Rust engine compiles Unicode classes to UTF-8
/// automata, so a pattern Go accepts (`\pL{1000}` needs about 30 MB) can
/// still be too big here: it then fails with Go's "expression too large".
const SIZE_LIMIT: usize = 128 << 20;
/// Nesting the printed HIR may reach: Go allows a tree 1,000 levels deep
/// and the printer adds at most a group per level.
const NEST_LIMIT: u32 = 4 * MAX_HEIGHT as u32;

/// Go `regexp.Compile(pat)`: an engine that matches as Go's would, or
/// Go's error text.
pub(crate) fn compile_go(pat: &str) -> Result<Regex, String> {
    let src = translate(pat)?;
    RegexBuilder::new(&src)
        .size_limit(SIZE_LIMIT)
        .nest_limit(NEST_LIMIT)
        .build()
        .map_err(|e| match e {
            regex::Error::CompiledTooBig(_) => go_error(ERR_LARGE, pat),
            _ => go_error(ERR_INTERNAL, pat),
        })
}

/// Go `Regexp.SubexpNames()` for an engine from `compile_go`: index 0 and
/// unnamed groups are `""`.
pub(crate) fn go_capture_names(re: &Regex) -> Vec<String> {
    re.capture_names()
        .map(|n| {
            n.and_then(|n| n.strip_prefix('_'))
                .and_then(|n| n.split_once('_'))
                .map_or_else(String::new, |(_, name)| name.to_string())
        })
        .collect()
}

/// Go `unicode.IsLetter(c) || unicode.IsDigit(c)` (categories L and Nd
/// from Go's tables): with `_`, what Go's `Regexp.Expand` reads as a
/// group name in a replacement.
pub(crate) fn go_letter_or_digit(c: char) -> bool {
    let t = tables();
    let c = c as i32;
    ["L", "Nd"].iter().any(|cat| {
        t.categories.get(cat).is_some_and(|runs| {
            let i = runs.partition_point(|&(_, hi)| hi < c);
            runs.get(i).is_some_and(|&(lo, _)| lo <= c)
        })
    })
}

