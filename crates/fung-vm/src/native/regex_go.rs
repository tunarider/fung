//! Regular expressions with Go semantics (Go `regexp.Compile`, Perl
//! flags) on the `regex` crate's engine.
//!
//! Go and Rust disagree on which patterns are valid (`(?x)`, `\Z`, `\Q..\E`,
//! `a**`, `x{1001}`, `\0`, `[a&&b]` ...) and on what some valid ones mean
//! (`\w` `\d` `\s` `\b` are ASCII in Go, `\<` is a literal `<`, `[[a]]` is a
//! class followed by `]`). Mapping one parser's results onto the other's
//! cannot give Go's first error and its exact text, so this module is a
//! step-by-step port of Go's parser (`regexp/syntax/parse.go`, Go 1.27):
//! the same scan, the same stack of partial expressions, the same
//! factoring of alternations and the same size and depth limits, with
//! nodes in an arena so that Go's free-list reuse (which its limit caches
//! depend on) happens the same way. A pattern Go rejects fails here with
//! Go's `err.Error()`.
//!
//! The finished Go tree becomes a `regex_syntax` HIR whose every piece is
//! explicit: classes as code point ranges computed with Go's tables
//! (`spec/regex_unicode.txt`, generated by Go: categories, scripts and
//! `unicode.SimpleFold` orbits, so Unicode 17 like Go), case-insensitive
//! literals as their fold orbit, word boundaries as ASCII. The HIR is
//! printed (`print_hir`, unambiguous: every repetition operand grouped)
//! and handed to `regex::RegexBuilder`.
//!
//! Capture names: Go allows duplicates and names starting with a digit,
//! Rust allows neither, so every named group gets the Rust name
//! `_<index>_<go name>`; `go_capture_names` gives back Go's
//! `SubexpNames()`.
//!
//! The parser is the definition of fung's regular-expression syntax and
//! stays after Go is gone (user decision 2026-10-16, to be revisited after
//! stage 6; open-questions "Rust 이전"). What only copies Go's accidents is
//! transitional (open-questions "Go 동등을 위한 과도기 잔가지"): Go's
//! Unicode tables (`spec/regex_unicode.txt`) and the Go error texts.

use std::collections::HashMap;
use std::sync::OnceLock;

use regex::{Regex, RegexBuilder};
use regex_syntax::hir::{self, Hir, Look};

// ---------------------------------------------------------------------
// Go's tables
