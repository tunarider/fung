//! `spec/builtins.txt`, generated from the Rust code: the prelude
//! natives with their parameter lists (`super::native_prelude`), the
//! members of the `_native.*` bridges (`super::NATIVE_MODULES`), the
//! public names of the prelude files written in fung with the parameters
//! of their functions (`extras::PRELUDE_FILES`; resolve checks calls
//! against them, D43), and the public functions of the standard
//! modules written in fung that the spec records (`conc`, `http`).
//!
//! The Rust tables are the source and the file is derived. The front end
//! reads the file ([`fung_front::builtins`]), so the generator does not
//! compile the extras against it: it builds the spec a step at a time,
//! natives and bridges first, then each prelude file and the modules,
//! compiling each against the spec built so far
//! ([`fung_front::loader::Loader::spec`]). A new prelude native or
//! `_native.*` bridge therefore needs no hand edit: add it to its table
//! and run the update.
//!
//! The test fails when the file differs from what the code gives;
//! `FUNG_UPDATE_SPEC=1 cargo test spec_file` rewrites it. (Other tests
//! check the booted runtime against the file: `boot/tests.rs`.)

use fung_front::builtins::{Builtins, parse};
use std::collections::BTreeMap;

use fung_front::bytecode::Proto;
use fung_front::extras;
use fung_front::loader::{Loader, Stage};
use fung_front::resolve::Sig;

use crate::testutil::on_big_stack;
use crate::value::{NativeParam, Value};

/// The standard modules written in fung whose public functions the spec
/// lists with their parameters.
const FUNG_MODULES: &[&str] = &["conc", "http"];

const HEADER: &str = "\
# fung built-in names. Generated by `FUNG_UPDATE_SPEC=1 cargo test spec_file`; do not edit.
# prelude native <name>(<params>)   native function (or plain value) of the prelude
# prelude fung <name>(<params>)     public name of a prelude file written in fung (a function with its parameters)
# module <module> <name>(<params>)  member of a _native.x bridge, or public function of conc or http
# ... pure                          a function known to have no effect: a call of it as a statement is E0234
";

fn native_params(ps: &[NativeParam]) -> String {
    ps.iter()
        .map(|p| {
            if p.rest {
                format!("...{}", p.name)
            } else if p.default.is_some() {
                format!("{}=?", p.name)
            } else {
                p.name.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// A native's line; `module` is where the effect tables list it
/// (`prelude` or the bridge), for the `pure` mark (D39).
fn native_line(prefix: &str, module: &str, name: &str, v: &Value) -> String {
    match v {
        Value::Native(n) => format!(
            "{prefix} {name}({}){}",
            native_params(&n.params),
            pure_mark(crate::vm::has_no_effect(module, name))
        ),
        _ => format!("{prefix} {name}"),
    }
}

fn pure_mark(pure: bool) -> &'static str {
    if pure { " pure" } else { "" }
}

/// The spec of `lines` (with the header), for the next step to compile
/// against. Leaked: the loader keeps a `'static` spec, and this runs only
/// in the generator's test.
fn spec_of(lines: &[String]) -> &'static Builtins {
    Box::leak(Box::new(parse(&format!("{HEADER}{}\n", lines.join("\n")))))
}

/// The public names of a compiled module body, each with its parameters
/// when resolve knows them (a top-level fn, or a member of a bridge under
/// a name of the file: the parameters calls are checked against, D43).
/// `fung_pure` says which functions written in fung only compute (VA47);
/// a function that is another name for a native has the native's mark.
fn export_lines(
    prefix: &str,
    proto: &Proto,
    sigs: &BTreeMap<String, Sig>,
    fung_pure: &dyn Fn(&str, bool) -> bool,
) -> Vec<String> {
    proto
        .exports
        .iter()
        .map(|name| match sigs.get(name) {
            Some(sig) => {
                let pure = fung_pure(name, sig.pure);
                format!("{prefix} {name}({}){}", sig.list(), pure_mark(pure))
            }
            None => format!("{prefix} {name}"),
        })
        .collect()
}

/// Whether the prelude function `name`, written in fung, only computes:
/// an alias carries its native's mark, and every other one is classified
/// by hand (`PURE_FUNG`, `CALLING_FUNG`), as the natives are.
fn prelude_fung_pure(name: &str, alias_pure: bool) -> bool {
    let pure = crate::vm::PURE_FUNG.contains(&name);
    let calling = crate::vm::CALLING_FUNG.contains(&name);
    assert!(
        usize::from(pure) + usize::from(calling) + usize::from(alias_pure) <= 1,
        "the prelude function `{name}` is classified twice"
    );
    assert!(
        pure || calling || alias_pure,
        "the prelude function `{name}` is not classified: add it to PURE_FUNG or CALLING_FUNG"
    );
    pure || alias_pure
}

/// The content `spec/builtins.txt` must have.
pub(crate) fn render() -> String {
    on_big_stack(|| {
        let mut lines = Vec::new();
        for (name, v) in &super::native_prelude(&[]).0 {
            lines.push(native_line("prelude native", "prelude", name, v));
        }
        for (key, module) in super::NATIVE_MODULES {
            let m = module();
            assert_eq!(m.key, *key);
            for name in m.names() {
                let v = m.get(name).expect(name);
                lines.push(native_line(&format!("module {key}"), key, name, v));
            }
        }
        for (name, src) in extras::PRELUDE_FILES {
            let loader = Loader {
                internal: true,
                library: true,
                spec: Some(spec_of(&lines)),
                ..Loader::default()
            };
            let file = extras::path(name);
            let (b, errs) = loader.compile(&file, src, Stage::All);
            assert!(errs.is_empty(), "{file}: {errs:?}");
            let proto = b.proto.expect("a compiled prelude file");
            lines.extend(export_lines(
                "prelude fung",
                &proto,
                &b.sigs,
                &prelude_fung_pure,
            ));
        }
        let loader = Loader {
            spec: Some(spec_of(&lines)),
            ..Loader::default()
        };
        let src: String = FUNG_MODULES
            .iter()
            .map(|m| format!("import {m}\n"))
            .chain(
                FUNG_MODULES
                    .iter()
                    .map(|m| format!("print(type_of({m}))\n")),
            )
            .collect();
        let (b, errs) = loader.compile("-e", &src, Stage::All);
        assert!(errs.is_empty(), "{errs:?}");
        for key in FUNG_MODULES {
            let m = b.modules.iter().find(|m| m.key == *key).expect(key);
            let proto = m.proto.as_ref().expect(key);
            lines.extend(export_lines(
                &format!("module {key}"),
                proto,
                &m.sigs,
                &|_, alias_pure| alias_pure,
            ));
        }
        lines.sort();
        format!("{HEADER}{}\n", lines.join("\n"))
    })
}
#[test]
fn spec_file_matches_the_tables() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../spec/builtins.txt");
    let want = render();
    if std::env::var_os("FUNG_UPDATE_SPEC").is_some() {
        std::fs::write(path, &want).expect(path);
        return;
    }
    let got = std::fs::read_to_string(path).expect(path);
    assert!(
        got == want,
        "spec/builtins.txt is out of date: run `FUNG_UPDATE_SPEC=1 cargo test spec_file`"
    );
}
