var update = flag.Bool("update", false, "rewrite spec/*.txt and crates/fung-vm/src/native/regex_go_fixtures.rs")

func params(ps []value.NativeParam) string {
	out := make([]string, len(ps))
	for i, p := range ps {
		switch {
		case p.Rest:
			out[i] = "..." + p.Name
		case p.Default != nil:
			out[i] = p.Name + "=?"
		default:
			out[i] = p.Name
		}
	}
	return strings.Join(out, ", ")
}

func builtinsSpec(t *testing.T) string {
	var lines []string
	natives := prelude.Core(nil)
	for k, v := range vm.Concurrency() {
		natives[k] = v
	}
	for name, v := range natives {
		n, ok := v.(*value.Native)
		if !ok {
			lines = append(lines, "prelude native "+name) // a non-function prelude value (args)
			continue
		}
		lines = append(lines, fmt.Sprintf("prelude native %s(%s)", name, params(n.Params)))
	}
	reg := extras.Default()
	for k, v := range vm.NativeModules() {
		reg.Natives[k] = v
	}
	src, _ := extras.Source("prelude")
	loader := &frontend.Loader{Prelude: natives, Natives: reg.Natives, Stdlib: reg.Stdlib, Internal: true}
	b, errs := loader.Compile("extras/prelude.fung", src, frontend.StageAll)
	if len(errs) > 0 {
		t.Fatalf("compile prelude.fung: %v", errs[0])
	}
	for _, name := range b.Proto.Exports {
		lines = append(lines, "prelude fung "+name)
	}
	mods := map[string]*value.Module{}
	for k, m := range native.Bridges() {
		mods[k] = m
	}
	for k, m := range vm.NativeModules() {
		mods[k] = m
	}
	for key, m := range mods {
		for _, name := range m.Names() {
			v, _ := m.Get(name)
			if n, ok := v.(*value.Native); ok {
				lines = append(lines, fmt.Sprintf("module %s %s(%s)", key, name, params(n.Params)))
			} else {
				lines = append(lines, fmt.Sprintf("module %s %s", key, name))
			}
		}
	}
	sort.Strings(lines)
	return "# fung built-in names. Generated by `go test ./tests -run TestSpecFiles -update`; do not edit.\n" +
		"# prelude native <name>(<params>)   Go function in the prelude\n" +
		"# prelude fung <name>               public name of extras/prelude.fung\n" +
		"# module <_native.x> <name>(<params>)\n" + strings.Join(lines, "\n") + "\n"
}

func errorsSpec(t *testing.T) string {
	var b strings.Builder
	b.WriteString("# fung error and warning catalog. Generated by `go test ./tests -run TestSpecFiles -update`; do not edit.\n")
	b.WriteString("# code<TAB>message template<TAB>underline label<TAB>help\n")
	for _, code := range diag.Codes() {
		fields := []string{code, diag.Template(code), diag.Label(code), diag.Hint(code)}
		for _, f := range fields {
			if strings.ContainsAny(f, "\t\n") {
				t.Fatalf("%s: a catalog field contains a tab or newline: %q", code, f)
			}
		}
		b.WriteString(strings.Join(fields, "\t") + "\n")
	}
	return b.String()
}

// unicodeClasses are the Go character classes the Rust port must match
// exactly: identifiers and plain map keys (letter, digit, upper), string
// quoting (print), and trimming (space).
var unicodeClasses = []struct {
	name string
	is   func(rune) bool
}{
	{"letter", unicode.IsLetter},
	{"digit", unicode.IsDigit},
	{"upper", unicode.IsUpper},
	{"print", unicode.IsPrint},
	{"space", unicode.IsSpace},
}

// unicodeSpec lists, per class, the maximal runs of code points for which
// the Go predicate holds. Asking the predicate for every code point (rather
// than copying the RangeTables) keeps the Latin-1 special cases of IsUpper,
// IsPrint and IsSpace.
func unicodeSpec() string {
	var b strings.Builder
	b.WriteString("# Go unicode classes. Generated by `go test ./tests -run TestSpecFiles -update`; do not edit.\n")
	fmt.Fprintf(&b, "# unicode.Version %s\n", unicode.Version)
	b.WriteString("# <class> <first> <last>   inclusive run of code points (hex) where unicode.Is<Class> holds\n")
	for _, c := range unicodeClasses {
		for lo := rune(0); lo <= unicode.MaxRune; lo++ {
			if !c.is(lo) {
				continue
			}
			hi := lo
			for hi+1 <= unicode.MaxRune && c.is(hi+1) {
				hi++
			}
			fmt.Fprintf(&b, "%s %04X %04X\n", c.name, lo, hi)
			lo = hi
		}
	}
	return b.String()
}

// regexUnicodeSpec lists the Unicode tables Go's regexp/syntax reads for
// \p{...} classes and case folding (Perl flags): unicode.Categories,
// FoldCategory, Scripts, FoldScript and CategoryAliases, and every
// unicode.SimpleFold orbit. The Rust port builds Go-semantics regular
// expressions from them (crates/fung-vm/src/native/regex_go.rs).
func regexUnicodeSpec() string {
	var b strings.Builder
	b.WriteString("# Go regexp Unicode tables. Generated by `go test ./tests -run TestSpecFiles -update`; do not edit.\n")
	fmt.Fprintf(&b, "# unicode.Version %s\n", unicode.Version)
	b.WriteString("# cat|foldcat|script|foldscript <name> <runs...>   unicode.Categories, FoldCategory, Scripts, FoldScript\n")
	b.WriteString("#   a run is <hex> or <hex>-<hex> (inclusive); strided table entries are spelled out\n")
	b.WriteString("# alias <name> <category>   unicode.CategoryAliases\n")
	b.WriteString("# fold <hex> <hex>...   one unicode.SimpleFold orbit, from its smallest code point, in SimpleFold order\n")
	tables := func(kind string, m map[string]*unicode.RangeTable) {
		names := make([]string, 0, len(m))
		for n := range m {
			names = append(names, n)
		}
		sort.Strings(names)
		for _, n := range names {
			b.WriteString(kind + " " + n)
			for _, r := range tableRuns(m[n]) {
				if r[0] == r[1] {
					fmt.Fprintf(&b, " %X", r[0])
				} else {
					fmt.Fprintf(&b, " %X-%X", r[0], r[1])
				}
			}
			b.WriteString("\n")
		}
	}
	tables("cat", unicode.Categories)
	tables("foldcat", unicode.FoldCategory)
	tables("script", unicode.Scripts)
	tables("foldscript", unicode.FoldScript)
	aliases := make([]string, 0, len(unicode.CategoryAliases))
	for a := range unicode.CategoryAliases {
		aliases = append(aliases, a)
	}
	sort.Strings(aliases)
	for _, a := range aliases {
		fmt.Fprintf(&b, "alias %s %s\n", a, unicode.CategoryAliases[a])
	}
	seen := map[rune]bool{}
	for c := rune(0); c <= unicode.MaxRune; c++ {
		if seen[c] || unicode.SimpleFold(c) == c {
			continue
		}
		fmt.Fprintf(&b, "fold %X", c)
		seen[c] = true
		for f := unicode.SimpleFold(c); f != c; f = unicode.SimpleFold(f) {
			fmt.Fprintf(&b, " %X", f)
			seen[f] = true
		}
		b.WriteString("\n")
	}
	return b.String()
}

// tableRuns turns a RangeTable into sorted maximal inclusive runs.
func tableRuns(t *unicode.RangeTable) [][2]rune {
	var out [][2]rune
	add := func(lo, hi rune) {
		if n := len(out); n > 0 && out[n-1][1]+1 == lo {
			out[n-1][1] = hi
			return
		}
		out = append(out, [2]rune{lo, hi})
	}
	for _, r := range t.R16 {
		for c := rune(r.Lo); c <= rune(r.Hi); c += rune(r.Stride) {
			if r.Stride == 1 {
				add(rune(r.Lo), rune(r.Hi))
				break
			}
			add(c, c)
		}
	}
	for _, r := range t.R32 {
		for c := rune(r.Lo); c <= rune(r.Hi); c += rune(r.Stride) {
			if r.Stride == 1 {
				add(rune(r.Lo), rune(r.Hi))
				break
			}
			add(c, c)
		}
	}
	return out
}

// The spec files are the language-neutral record of built-in names and
// error messages; the Rust port reads them. They must match the Go code.
func TestSpecFiles(t *testing.T) {
	for path, want := range map[string]string{"../spec/builtins.txt": builtinsSpec(t), "../spec/errors.txt": errorsSpec(t), "../spec/unicode.txt": unicodeSpec(), "../spec/regex_unicode.txt": regexUnicodeSpec()} {
		if *update {
			if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		got, err := os.ReadFile(path)
		if err != nil || string(got) != want {
			t.Errorf("%s is out of date: run `go test ./tests -run TestSpecFiles -update`", path)
		}
	}
}
